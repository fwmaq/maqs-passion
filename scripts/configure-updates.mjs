/**
 * Configure public GitHub Releases endpoint and public Tauri updater signing key.
 * Never commits or reads the private signing key.
 * Usage: npm run updates:configure -- --repo OWNER/REPO --pubkey C:\path\my.key.pub
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
const argv=process.argv.slice(2);
const valueOf=(name)=>{const i=argv.indexOf(name);return i<0?'':argv[i+1]??''};
const repo=valueOf('--repo').trim();
const pubkeyPath=valueOf('--pubkey');
if(!/^[\w.-]+\/[\w.-]+$/.test(repo)||!pubkeyPath){
  console.error('Usage: npm run updates:configure -- --repo OWNER/REPO --pubkey "C:\\path\\maqs-passion.key.pub"');
  process.exit(1);
}
const publicKey=readFileSync(resolve(pubkeyPath),'utf8').trim();
if(!publicKey.includes('RWQ') && !publicKey.includes('RWT') && !publicKey.includes('RWS')) {
  // Tauri minisign public keys typically contain RWQ... / RWT...; warn but still allow
  // other valid keys emitted by newer Tauri signer versions.
  console.warn('Warning: double-check this is the PUBLIC .key.pub file generated by Tauri.');
}
if(!publicKey||publicKey.includes('PRIVATE KEY')) throw new Error('Expected a nonempty public key (not the private key).');
const confPath=resolve('src-tauri/tauri.conf.json');
const conf=JSON.parse(readFileSync(confPath,'utf8'));
conf.plugins??={};
conf.plugins.updater={
  pubkey:publicKey,
  endpoints:[`https://github.com/${repo}/releases/latest/download/latest.json`],
  windows:{installMode:'passive'},
};
conf.bundle.createUpdaterArtifacts=true;
conf.bundle.windows??={};
conf.bundle.windows.nsis??={};
conf.bundle.windows.nsis.installMode='currentUser';
writeFileSync(confPath,JSON.stringify(conf,null,2)+'\n');
const viewPath=resolve('src/update-config.json');
writeFileSync(viewPath,JSON.stringify({configured:true,repository:repo,releaseUrl:`https://github.com/${repo}/releases/latest`},null,2)+'\n');
mkdirSync(resolve('src-tauri'),{recursive:true});
writeFileSync(resolve('src-tauri/updater-public.key'),publicKey+'\n');
console.log(`Configured signed updates via https://github.com/${repo}/releases`);
console.log('Commit tauri.conf.json, src/update-config.json, and updater-public.key (PUBLIC only).');
console.log('NEVER commit your .key private signing key.');
